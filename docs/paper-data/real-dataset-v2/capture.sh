#!/usr/bin/env bash
# Captures the two multi-UE scenarios this directory documents, against a
# live Open5GS + UERANSIM core. Run as root from a machine where that core is
# already up with four registered subscribers and four attached UEs -- see
# README.md for the exact lab build.
#
# Why a script and not a transcript: the point of these captures is that the
# flooding subscriber and the well-behaved ones are indistinguishable by
# source IP, which only holds if they genuinely run concurrently through the
# same gNB. That is a timing property, and timing properties don't survive
# being described in prose.
set -euo pipefail

OUT_DIR="${OUT_DIR:-$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)}"
UERANSIM_BIN="${UERANSIM_BIN:-/home/felipe/UERANSIM/build}"
GATEWAY="${GATEWAY:-10.45.0.1}"

# Snaplen 128 is enough for Ethernet + IPv4 + UDP + a full GTP-U header with
# the optional block and one extension header (58 bytes), with headroom. The
# user-plane payload is irrelevant to every measurement here, and keeping it
# would multiply the committed size for nothing.
SNAPLEN=128

# Packet counts rather than durations, so tcpdump terminates on its own: a
# capture stopped by a signal can lose its buffered tail, and these files are
# committed artifacts.
NORMAL_PACKETS="${NORMAL_PACKETS:-5000}"
FLOOD_PACKETS="${FLOOD_PACKETS:-20000}"

# The flooding UE's rate. The tunnel itself sustains ~125,000 pkt/s
# (measured on this lab with iperf3 straight over loopback), so 3,000 is
# deliberately far below the ceiling -- three times
# GTPU_TUNNEL_FLOOD_PPS's 1000 default, which is what the measurement needs,
# without producing a pcap too large to commit.
FLOOD_PPS="${FLOOD_PPS:-3000}"
FLOOD_SECONDS="${FLOOD_SECONDS:-12}"

NORMAL_INTERVAL=0.1

tuns=()
while read -r t; do tuns+=("$t"); done < <(ip -o link show | grep -oE 'uesimtun[0-9]+' | sort -u)
if [ "${#tuns[@]}" -lt 4 ]; then
  echo "need 4 attached UEs, found ${#tuns[@]}: ${tuns[*]-none}" >&2
  exit 1
fi
echo "UE tunnels: ${tuns[*]}"

tun_addr() { ip -o -4 addr show "$1" | awk '{print $4}' | cut -d/ -f1; }

# ---------------------------------------------------------------- scenario 1
# Four subscribers, all behaving. The baseline every threshold is judged
# against, and the evidence that four distinct TEIDs share one source IP.
echo "capturing multi_ue_normal (${NORMAL_PACKETS} packets) ..."
rm -f "$OUT_DIR/multi_ue_normal.pcap"
for t in "${tuns[@]}"; do
  ( ping -I "$t" -i "$NORMAL_INTERVAL" -c 2000 "$GATEWAY" >/dev/null 2>&1 || true ) &
done
tcpdump -i lo -n -s "$SNAPLEN" -c "$NORMAL_PACKETS" -w "$OUT_DIR/multi_ue_normal.pcap" 'udp port 2152' 2>&1 | tail -2
pkill -INT -x ping || true
wait || true

# ---------------------------------------------------------------- scenario 2
# The decisive one: three subscribers behaving, one flooding, all through the
# same gNB and therefore the same source IP. A per-source counter sees a
# single number here and cannot attribute it; a per-TEID counter can.
#
# The flood is generated by gen_tunnel_flood.py, not iperf3 -- read that
# script's docstring before substituting anything else. Two obvious choices
# (iperf3's -B, and UERANSIM's own nr-binder) both fail SILENTLY here,
# reporting a perfectly successful transfer while not a single packet enters
# the GTP-U tunnel.
echo "capturing multi_ue_one_flooding (${FLOOD_PACKETS} packets) ..."
rm -f "$OUT_DIR/multi_ue_one_flooding.pcap"
for t in "${tuns[@]:1}"; do
  ( ping -I "$t" -i "$NORMAL_INTERVAL" -c 2000 "$GATEWAY" >/dev/null 2>&1 || true ) &
done
( "$(dirname "${BASH_SOURCE[0]}")/gen_tunnel_flood.py" \
    --device "${tuns[0]}" --dest "$GATEWAY" \
    --pps "$FLOOD_PPS" --seconds "$FLOOD_SECONDS" >/dev/null 2>&1 || true ) &

tcpdump -i lo -n -s "$SNAPLEN" -c "$FLOOD_PACKETS" -w "$OUT_DIR/multi_ue_one_flooding.pcap" 'udp port 2152' 2>&1 | tail -2
pkill -INT -x ping || true
pkill -x iperf3 || true
wait || true

chmod 644 "$OUT_DIR"/*.pcap
ls -la "$OUT_DIR"/*.pcap
